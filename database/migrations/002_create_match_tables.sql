-- Calendrier, résultats, événements de match, classement et tactiques.

CREATE TABLE `fixtures` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `save_id` BIGINT UNSIGNED NOT NULL,
    `season_id` BIGINT UNSIGNED NOT NULL,
    `league_id` BIGINT UNSIGNED NOT NULL,
    `round_number` SMALLINT UNSIGNED NOT NULL,
    `leg` ENUM('first', 'second') NOT NULL DEFAULT 'first',
    `matchday` SMALLINT UNSIGNED NOT NULL,
    `scheduled_at` DATETIME NOT NULL,
    `home_club_id` BIGINT UNSIGNED NOT NULL,
    `away_club_id` BIGINT UNSIGNED NOT NULL,
    `status` ENUM('scheduled', 'live', 'halftime', 'finished', 'postponed', 'cancelled') NOT NULL DEFAULT 'scheduled',
    `current_minute` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `home_score` TINYINT UNSIGNED NULL DEFAULT NULL,
    `away_score` TINYINT UNSIGNED NULL DEFAULT NULL,
    `attendance` INT UNSIGNED NULL DEFAULT NULL,
    `statistics` JSON NULL,
    `started_at` DATETIME NULL DEFAULT NULL,
    `finished_at` DATETIME NULL DEFAULT NULL,
    `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_fixtures_pairing` (`season_id`, `league_id`, `matchday`, `home_club_id`, `away_club_id`),
    KEY `idx_fixtures_save_date` (`save_id`, `scheduled_at`),
    KEY `idx_fixtures_save_status` (`save_id`, `status`),
    KEY `idx_fixtures_home_club` (`home_club_id`),
    KEY `idx_fixtures_away_club` (`away_club_id`),
    KEY `idx_fixtures_league` (`league_id`),
    CONSTRAINT `fk_fixtures_save` FOREIGN KEY (`save_id`) REFERENCES `saves` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_fixtures_season` FOREIGN KEY (`season_id`) REFERENCES `seasons` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_fixtures_league` FOREIGN KEY (`league_id`) REFERENCES `leagues` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_fixtures_home_club` FOREIGN KEY (`home_club_id`) REFERENCES `clubs` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_fixtures_away_club` FOREIGN KEY (`away_club_id`) REFERENCES `clubs` (`id`) ON DELETE CASCADE,
    CONSTRAINT `chk_fixtures_distinct_clubs` CHECK (`home_club_id` <> `away_club_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `match_events` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `save_id` BIGINT UNSIGNED NOT NULL,
    `fixture_id` BIGINT UNSIGNED NOT NULL,
    `club_id` BIGINT UNSIGNED NULL DEFAULT NULL,
    `player_id` BIGINT UNSIGNED NULL DEFAULT NULL,
    `related_player_id` BIGINT UNSIGNED NULL DEFAULT NULL,
    `minute` SMALLINT UNSIGNED NOT NULL,
    `added_time` TINYINT UNSIGNED NOT NULL DEFAULT 0,
    `type` VARCHAR(40) NOT NULL,
    `description` TEXT NOT NULL,
    `data` JSON NULL,
    `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    KEY `idx_match_events_save_fixture_minute` (`save_id`, `fixture_id`, `minute`, `added_time`),
    KEY `idx_match_events_player` (`player_id`),
    KEY `idx_match_events_related_player` (`related_player_id`),
    KEY `idx_match_events_club` (`club_id`),
    CONSTRAINT `fk_match_events_save` FOREIGN KEY (`save_id`) REFERENCES `saves` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_match_events_fixture` FOREIGN KEY (`fixture_id`) REFERENCES `fixtures` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_match_events_club` FOREIGN KEY (`club_id`) REFERENCES `clubs` (`id`) ON DELETE SET NULL,
    CONSTRAINT `fk_match_events_player` FOREIGN KEY (`player_id`) REFERENCES `players` (`id`) ON DELETE SET NULL,
    CONSTRAINT `fk_match_events_related_player` FOREIGN KEY (`related_player_id`) REFERENCES `players` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `standings` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `save_id` BIGINT UNSIGNED NOT NULL,
    `season_id` BIGINT UNSIGNED NOT NULL,
    `league_id` BIGINT UNSIGNED NOT NULL,
    `club_id` BIGINT UNSIGNED NOT NULL,
    `position` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `played` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `wins` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `draws` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `losses` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `goals_for` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `goals_against` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `goal_difference` SMALLINT NOT NULL DEFAULT 0,
    `points` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `form` VARCHAR(10) NOT NULL DEFAULT '',
    `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_standings_season_club` (`season_id`, `club_id`),
    KEY `idx_standings_save_league_position` (`save_id`, `league_id`, `position`),
    KEY `idx_standings_league` (`league_id`),
    KEY `idx_standings_club` (`club_id`),
    CONSTRAINT `fk_standings_save` FOREIGN KEY (`save_id`) REFERENCES `saves` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_standings_season` FOREIGN KEY (`season_id`) REFERENCES `seasons` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_standings_league` FOREIGN KEY (`league_id`) REFERENCES `leagues` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_standings_club` FOREIGN KEY (`club_id`) REFERENCES `clubs` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `tactics` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `save_id` BIGINT UNSIGNED NOT NULL,
    `club_id` BIGINT UNSIGNED NOT NULL,
    `fixture_id` BIGINT UNSIGNED NULL DEFAULT NULL,
    `name` VARCHAR(100) NOT NULL DEFAULT 'Tactique principale',
    `formation` VARCHAR(20) NOT NULL,
    `mentality` ENUM('very_defensive', 'defensive', 'balanced', 'attacking', 'very_attacking') NOT NULL DEFAULT 'balanced',
    `playing_style` ENUM('possession', 'direct', 'counter', 'wings', 'long_ball', 'mixed') NOT NULL DEFAULT 'mixed',
    `pressing` ENUM('low', 'medium', 'high') NOT NULL DEFAULT 'medium',
    `defensive_line` ENUM('deep', 'normal', 'high') NOT NULL DEFAULT 'normal',
    `tempo` ENUM('slow', 'normal', 'fast') NOT NULL DEFAULT 'normal',
    `width` ENUM('narrow', 'normal', 'wide') NOT NULL DEFAULT 'normal',
    `lineup` JSON NOT NULL,
    `substitutes` JSON NULL,
    `individual_instructions` JSON NULL,
    `captain_player_id` BIGINT UNSIGNED NULL DEFAULT NULL,
    `penalty_taker_id` BIGINT UNSIGNED NULL DEFAULT NULL,
    `free_kick_taker_id` BIGINT UNSIGNED NULL DEFAULT NULL,
    `is_default` TINYINT(1) NOT NULL DEFAULT 0,
    `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_tactics_fixture_club` (`fixture_id`, `club_id`),
    KEY `idx_tactics_save_club_default` (`save_id`, `club_id`, `is_default`),
    KEY `idx_tactics_club` (`club_id`),
    KEY `idx_tactics_captain` (`captain_player_id`),
    KEY `idx_tactics_penalty_taker` (`penalty_taker_id`),
    KEY `idx_tactics_free_kick_taker` (`free_kick_taker_id`),
    CONSTRAINT `fk_tactics_save` FOREIGN KEY (`save_id`) REFERENCES `saves` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_tactics_club` FOREIGN KEY (`club_id`) REFERENCES `clubs` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_tactics_fixture` FOREIGN KEY (`fixture_id`) REFERENCES `fixtures` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_tactics_captain` FOREIGN KEY (`captain_player_id`) REFERENCES `players` (`id`) ON DELETE SET NULL,
    CONSTRAINT `fk_tactics_penalty_taker` FOREIGN KEY (`penalty_taker_id`) REFERENCES `players` (`id`) ON DELETE SET NULL,
    CONSTRAINT `fk_tactics_free_kick_taker` FOREIGN KEY (`free_kick_taker_id`) REFERENCES `players` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
