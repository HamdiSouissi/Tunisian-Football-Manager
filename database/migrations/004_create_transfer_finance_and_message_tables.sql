-- Mercato, prêts, finances, objectifs, messagerie et paramètres de partie.

CREATE TABLE `transfers` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `save_id` BIGINT UNSIGNED NOT NULL,
    `season_id` BIGINT UNSIGNED NULL DEFAULT NULL,
    `player_id` BIGINT UNSIGNED NOT NULL,
    `from_club_id` BIGINT UNSIGNED NULL DEFAULT NULL,
    `to_club_id` BIGINT UNSIGNED NULL DEFAULT NULL,
    `type` ENUM('permanent', 'free', 'loan', 'loan_return', 'youth') NOT NULL,
    `fee` DECIMAL(15,2) NOT NULL DEFAULT 0.00,
    `agent_fee` DECIMAL(15,2) NOT NULL DEFAULT 0.00,
    `status` ENUM('pending', 'completed', 'cancelled') NOT NULL DEFAULT 'pending',
    `transfer_date` DATE NOT NULL,
    `completed_at` DATETIME NULL DEFAULT NULL,
    `details` JSON NULL,
    `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    KEY `idx_transfers_save_date` (`save_id`, `transfer_date`),
    KEY `idx_transfers_save_player` (`save_id`, `player_id`),
    KEY `idx_transfers_player` (`player_id`),
    KEY `idx_transfers_from_club` (`from_club_id`),
    KEY `idx_transfers_to_club` (`to_club_id`),
    KEY `idx_transfers_season` (`season_id`),
    CONSTRAINT `fk_transfers_save` FOREIGN KEY (`save_id`) REFERENCES `saves` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_transfers_season` FOREIGN KEY (`season_id`) REFERENCES `seasons` (`id`) ON DELETE SET NULL,
    CONSTRAINT `fk_transfers_player` FOREIGN KEY (`player_id`) REFERENCES `players` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_transfers_from_club` FOREIGN KEY (`from_club_id`) REFERENCES `clubs` (`id`) ON DELETE SET NULL,
    CONSTRAINT `fk_transfers_to_club` FOREIGN KEY (`to_club_id`) REFERENCES `clubs` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `transfer_offers` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `save_id` BIGINT UNSIGNED NOT NULL,
    `parent_offer_id` BIGINT UNSIGNED NULL DEFAULT NULL,
    `player_id` BIGINT UNSIGNED NOT NULL,
    `from_club_id` BIGINT UNSIGNED NULL DEFAULT NULL,
    `to_club_id` BIGINT UNSIGNED NULL DEFAULT NULL,
    `initiated_by` ENUM('user', 'ai') NOT NULL,
    `offer_type` ENUM('purchase', 'loan') NOT NULL DEFAULT 'purchase',
    `amount` DECIMAL(15,2) NOT NULL DEFAULT 0.00,
    `wage` DECIMAL(13,2) NULL DEFAULT NULL,
    `contract_years` TINYINT UNSIGNED NULL DEFAULT NULL,
    `signing_bonus` DECIMAL(15,2) NOT NULL DEFAULT 0.00,
    `loan_duration_months` TINYINT UNSIGNED NULL DEFAULT NULL,
    `loan_wage_share` DECIMAL(5,2) NULL DEFAULT NULL,
    `buy_option` DECIMAL(15,2) NULL DEFAULT NULL,
    `status` ENUM('pending', 'accepted', 'rejected', 'countered', 'withdrawn', 'expired') NOT NULL DEFAULT 'pending',
    `message` TEXT NULL,
    `expires_at` DATETIME NULL DEFAULT NULL,
    `responded_at` DATETIME NULL DEFAULT NULL,
    `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    KEY `idx_transfer_offers_save_player_status` (`save_id`, `player_id`, `status`),
    KEY `idx_transfer_offers_player` (`player_id`),
    KEY `idx_transfer_offers_to_club_status` (`to_club_id`, `status`),
    KEY `idx_transfer_offers_from_club` (`from_club_id`),
    KEY `idx_transfer_offers_parent` (`parent_offer_id`),
    KEY `idx_transfer_offers_expiry` (`expires_at`),
    CONSTRAINT `fk_transfer_offers_save` FOREIGN KEY (`save_id`) REFERENCES `saves` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_transfer_offers_parent` FOREIGN KEY (`parent_offer_id`) REFERENCES `transfer_offers` (`id`) ON DELETE SET NULL,
    CONSTRAINT `fk_transfer_offers_player` FOREIGN KEY (`player_id`) REFERENCES `players` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_transfer_offers_from_club` FOREIGN KEY (`from_club_id`) REFERENCES `clubs` (`id`) ON DELETE SET NULL,
    CONSTRAINT `fk_transfer_offers_to_club` FOREIGN KEY (`to_club_id`) REFERENCES `clubs` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `loans` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `save_id` BIGINT UNSIGNED NOT NULL,
    `transfer_id` BIGINT UNSIGNED NULL DEFAULT NULL,
    `player_id` BIGINT UNSIGNED NOT NULL,
    `from_club_id` BIGINT UNSIGNED NOT NULL,
    `to_club_id` BIGINT UNSIGNED NOT NULL,
    `starts_on` DATE NOT NULL,
    `ends_on` DATE NOT NULL,
    `wage_share` DECIMAL(5,2) NOT NULL DEFAULT 100.00,
    `option_to_buy` DECIMAL(15,2) NULL DEFAULT NULL,
    `status` ENUM('active', 'completed', 'terminated') NOT NULL DEFAULT 'active',
    `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    KEY `idx_loans_save_player_status` (`save_id`, `player_id`, `status`),
    KEY `idx_loans_player` (`player_id`),
    KEY `idx_loans_save_end_date` (`save_id`, `ends_on`),
    KEY `idx_loans_transfer` (`transfer_id`),
    KEY `idx_loans_from_club` (`from_club_id`),
    KEY `idx_loans_to_club` (`to_club_id`),
    CONSTRAINT `fk_loans_save` FOREIGN KEY (`save_id`) REFERENCES `saves` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_loans_transfer` FOREIGN KEY (`transfer_id`) REFERENCES `transfers` (`id`) ON DELETE SET NULL,
    CONSTRAINT `fk_loans_player` FOREIGN KEY (`player_id`) REFERENCES `players` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_loans_from_club` FOREIGN KEY (`from_club_id`) REFERENCES `clubs` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_loans_to_club` FOREIGN KEY (`to_club_id`) REFERENCES `clubs` (`id`) ON DELETE CASCADE,
    CONSTRAINT `chk_loans_distinct_clubs` CHECK (`from_club_id` <> `to_club_id`),
    CONSTRAINT `chk_loans_wage_share` CHECK (`wage_share` BETWEEN 0 AND 100)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

